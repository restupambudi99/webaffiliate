import { createRequire } from 'node:module';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const bundled = createRequire('C:/Users/Meta/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json');
const { chromium } = bundled('playwright');
const base = process.env.PREVIEW_QA_URL || 'http://127.0.0.1:4322';
const manifest = JSON.parse(await readFile('dist-preview/preview-manifest.json', 'utf8'));
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const failedRequests = [];
page.on('requestfailed', (request) => failedRequests.push(request.url()));
await mkdir('artifacts', { recursive: true });
for (const width of [360, 768, 1440]) {
  await page.setViewportSize({ width, height: 1000 });
  await page.goto(base + '/', { waitUntil: 'networkidle' });
  assert.equal(await page.title(), 'Desk Edit — Make room for better work');
  assert.equal(await page.locator('meta[name=robots]').getAttribute('content'), 'noindex, nofollow');
  assert.equal(await page.locator('.hero-photo').evaluate((image) => image.complete && image.naturalWidth > 0), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Preview overflow at ${width}`);
  if (width !== 768) await page.screenshot({ path: `artifacts/preview-home-${width}.png`, fullPage: true });
  await page.goto(base + '/articles/small-space-desk-setup/', { waitUntil: 'networkidle' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Article overflow at ${width}`);
}
await page.setViewportSize({ width: 360, height: 800 });
await page.goto(base + '/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Open navigation' }).click();
assert.equal(await page.locator('#mobile-nav').isVisible(), true);
await page.keyboard.press('Escape');
assert.equal(await page.locator('#mobile-nav').isVisible(), false);
await page.goto(base + '/guides/?category=lighting', { waitUntil: 'networkidle' });
assert.equal(await page.locator('.guide-card').count(), 1);
await page.getByRole('link', { name: 'All guides', exact: true }).first().click();
assert.equal(await page.locator('.guide-card').count(), 10);
await page.goBack({ waitUntil: 'networkidle' });
assert.equal(await page.locator('.guide-card').count(), 1);
await page.goto(base + '/search/?q=lamp', { waitUntil: 'networkidle' });
assert.match(await page.locator('.search-count').innerText(), /[1-9]\d* guides? found/);
await page.getByRole('searchbox', { name: 'Search guides' }).fill('unlikely-no-match-908');
await page.getByRole('button', { name: 'Search', exact: true }).click();
assert.equal(await page.locator('.guide-card').count(), 0);
assert.equal(await page.locator('.empty-state').isVisible(), true);
await page.getByRole('searchbox', { name: 'Search guides' }).fill('');
await page.getByRole('button', { name: 'Search', exact: true }).click();
assert.equal(await page.locator('.guide-card').count(), 10);
for (const path of manifest.pages.filter((path) => path !== '/404/')) {
  const response = await page.goto(base + path, { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200, path);
  assert.equal(await page.locator('meta[name=robots]').getAttribute('content'), 'noindex, nofollow', path);
}
assert.equal((await page.goto(base + '/does-not-exist/')).status(), 404);
assert.equal(await page.locator('a[rel~=sponsored]').count(), 0);
assert.deepEqual(errors, []);
assert.deepEqual(failedRequests, []);
const report = { testedAt: new Date().toISOString(), pages: manifest.pages.length, articleCount: manifest.articleCount, viewports: [360, 768, 1440], navigation: 'passed', categoryFilter: 'passed', history: 'passed', search: 'passed', previewNoindex: 'passed', browserErrors: errors, failedRequests };
await writeFile('artifacts/preview-qa.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
await browser.close();
